/* Move what is in data/*.json into D1, once.
 *
 * Writes db/seed.sql rather than talking to the database itself, so the
 * import can be read before it is run and run again against local and then
 * remote. It is idempotent: every row is an upsert keyed on the id the
 * event already has, so running it twice changes nothing the second time.
 *
 *   node scripts/seed-from-json.mjs
 *   npx wrangler d1 execute sjvsc --local --file db/seed.sql
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p, fallback) => {
  const file = join(root, p);
  if (!existsSync(file)) return fallback;
  try { return JSON.parse(readFileSync(file, 'utf8')); } catch { return fallback; }
};

/* SQLite takes a doubled quote as a literal one. Nothing else needs escaping
   inside a string literal, but a stray NUL would truncate it. */
const q = (v) =>
  v === null || v === undefined || v === ''
    ? 'NULL'
    : `'${String(v).replace(/\0/g, '').replace(/'/g, "''")}'`;

const qs = (v) => `'${String(v ?? '').replace(/\0/g, '').replace(/'/g, "''")}'`;
const list = (v) => qs(JSON.stringify(Array.isArray(v) ? v : []));

const lines = [
  '-- Generated by scripts/seed-from-json.mjs. Safe to run more than once.',
  '-- Source: data/events.json, data/saved.json, data/rates.json, data/gallery.json',
  '',
];

function eventRows(items, shelf, label) {
  if (!items.length) return;
  lines.push(`-- ${label}: ${items.length}`);
  for (const e of items) {
    const id = e.id || `${(e.title || 'event').toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
    lines.push(
      `INSERT INTO events (id, title, note, description, image, link, page,
  event_date, event_time, adv_from, adv_until, tickprice, tickfrom, tickto,
  details, attachments, ticksellers, shelf, updated_by)
VALUES (${qs(id)}, ${qs(e.title)}, ${qs(e.note)}, ${qs(e.desc)}, ${q(e.image)},
  ${q(e.link)}, ${qs(e.page)}, ${qs(e.date)}, ${qs(e.time)}, ${q(e.from)},
  ${q(e.until)}, ${qs(e.tickprice)}, ${q(e.tickfrom)}, ${q(e.tickto)},
  ${list(e.details)}, ${list(e.attachments)}, ${list(e.ticksellers)},
  ${shelf}, 'seed')
ON CONFLICT (id) DO UPDATE SET
  title = excluded.title, note = excluded.note, description = excluded.description,
  image = excluded.image, link = excluded.link, page = excluded.page,
  event_date = excluded.event_date, event_time = excluded.event_time,
  adv_from = excluded.adv_from, adv_until = excluded.adv_until,
  tickprice = excluded.tickprice, tickfrom = excluded.tickfrom,
  tickto = excluded.tickto, details = excluded.details,
  attachments = excluded.attachments, ticksellers = excluded.ticksellers,
  shelf = excluded.shelf, updated_at = datetime('now');`,
      ''
    );
  }
}

eventRows(read('data/events.json', []), 0, 'events on the calendar');
eventRows(read('data/saved.json', []), 1, 'events on the shelf');

const rates = read('data/rates.json', null);
if (rates) {
  lines.push('-- the rate card, as the one active version');
  lines.push(`UPDATE rate_cards SET active = 0 WHERE active = 1;`);
  lines.push(
    `INSERT INTO rate_cards (data, active, created_by) VALUES (${qs(JSON.stringify(rates))}, 1, 'seed');`,
    ''
  );
}

const gallery = read('data/gallery.json', null);
if (gallery && typeof gallery === 'object') {
  const slugs = Object.keys(gallery);
  lines.push(`-- galleries: ${slugs.length}`);
  for (const slug of slugs) {
    lines.push(
      `INSERT INTO gallery (slug, data, updated_by) VALUES (${qs(slug)}, ${qs(JSON.stringify(gallery[slug]))}, 'seed')
ON CONFLICT (slug) DO UPDATE SET data = excluded.data, updated_at = datetime('now');`
    );
  }
  lines.push('');
}

mkdirSync(join(root, 'db'), { recursive: true });
writeFileSync(join(root, 'db', 'seed.sql'), lines.join('\n'), 'utf8');

const counts = {
  events: read('data/events.json', []).length,
  shelf: read('data/saved.json', []).length,
  rateCard: rates ? 1 : 0,
  galleries: gallery ? Object.keys(gallery).length : 0,
};
console.log('db/seed.sql written:', JSON.stringify(counts));
